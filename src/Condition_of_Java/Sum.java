package Condition_of_Java;

public class Sum {
    public static void main(String[] args)  {
        int a = 5 ;   int b = 5 ;
        int sum = a + b ;
        int sub = a-b ;
        int multi = a* b ;
        int div = a/b ;
        int mod = a%b ;
        System.out.println("sum of a and b = "+sum + "\n Subtraction of a and b is "+sub + "\n Multiplication of a and b is "+multi + "\n Division of a and b is "+div + "\n modulus of a and b is " +mod);
    }
}
